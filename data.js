// 탁음/반탁음: 유니코드상 원래 글자 +1(゛), +2(゜)
const DAKU_RULE = [
  ['か','g',['가','기','구','게','고']],
  ['さ','z',['자','지','즈','제','조']],
  ['た','d',['다','지','즈','데','도']],
  ['は','b',['바','비','부','베','보']]
];
const VOWELS = ['a','i','u','e','o'];
const DAKU_FIX = { zi:'ji', di:'ji', du:'zu' };

function buildDaku(kata) {
  const base = kata ? KATA : HIRA;
  const out = [];
  DAKU_RULE.forEach(([start, cons, ko]) => {
    const i0 = HIRA.findIndex(x => x[0] === start);
    for (let j = 0; j < 5; j++) {
      const b = base[i0 + j][0];
      let r = cons + VOWELS[j]; r = DAKU_FIX[r] || r;
      out.push([String.fromCharCode(b.charCodeAt(0) + 1), r, ko[j], '', `${b}(${base[i0 + j][1]}) + ゛(점 두 개) → 탁한 소리 <b>${r}</b>`]);
    }
  });
  const iH = HIRA.findIndex(x => x[0] === 'は');
  const pko = ['파','피','푸','페','포'];
  for (let j = 0; j < 5; j++) {
    const b = base[iH + j][0];
    out.push([String.fromCharCode(b.charCodeAt(0) + 2), 'p' + VOWELS[j], pko[j], '', `${b}(${base[iH + j][1]}) + ゜(동그라미) → 터지는 소리 <b>p${VOWELS[j]}</b>`]);
  }
  return out;
}

// 요음: い단 글자 + 작은 ゃゅょ
const YOON_BASE = [
  ['き','ky',['캬','큐','쿄']],['し','sh',['샤','슈','쇼']],['ち','ch',['챠','츄','쵸']],
  ['に','ny',['냐','뉴','뇨']],['ひ','hy',['햐','휴','효']],['み','my',['먀','뮤','묘']],
  ['り','ry',['랴','류','료']],['ぎ','gy',['갸','규','교']],['じ','j',['쟈','쥬','죠']],
  ['び','by',['뱌','뷰','뵤']],['ぴ','py',['퍄','퓨','표']]
];
function buildYoon(kata) {
  const off = kata ? 0x60 : 0;
  const smalls = ['ゃ','ゅ','ょ'];
  const out = [];
  YOON_BASE.forEach(([b, c, ko]) => {
    const bb = String.fromCharCode(b.charCodeAt(0) + off);
    smalls.forEach((s, j) => {
      const ss = String.fromCharCode(s.charCodeAt(0) + off);
      const r = c + ['a','u','o'][j];
      out.push([bb + ss, r, ko[j], '', `${bb} + 작은 ${ss} → 한 박자로 붙여서 <b>${r}</b>`]);
    });
  });
  return out;
}

